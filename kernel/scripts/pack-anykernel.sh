#!/usr/bin/env bash
# shellcheck shell=bash
#
# 把裸 arm64 Image 打成 AnyKernel3 可刷入 zip（nabu）。
#
#   kernel/scripts/pack-anykernel.sh <Image> [branch] [sha]
#
# 为什么用 AnyKernel3 而不是自己写 updater-script：nabu 的 boot.img 是 header v3、
# 原始未压缩 Image、DTB 在 vendor_boot 里。AnyKernel3 只替换 boot 分区里的内核段，
# 保留原 header/ramdisk/cmdline，等于"把改内核这件事的影响面压到最小"。
set -euo pipefail

IMAGE="${1:?usage: pack-anykernel.sh <Image> [branch] [sha]}"
BRANCH="${2:-unknown}"
SHA="${3:-unknown}"
OUTDIR="${OUTDIR:-$PWD/out}"
WORK="${WORK:-$PWD/ak3}"
DEVICE="${DEVICE:-nabu}"

[ -f "$IMAGE" ] || { echo "ERROR: $IMAGE 不存在" >&2; exit 1; }
mkdir -p "$OUTDIR"

rm -rf "$WORK"
git clone --depth 1 https://github.com/osm0sis/AnyKernel3.git "$WORK" \
  || { echo "ERROR: clone AnyKernel3 失败（需要网络）" >&2; exit 1; }
rm -rf "$WORK/.git" "$WORK/.github"
cp "$IMAGE" "$WORK/Image"
rm -f "$WORK"/*.zip "$WORK/placeholder" 2>/dev/null || true

cat > "$WORK/anykernel.sh" <<EOF
### AnyKernel3 Ramdisk Mod Script
## ${DEVICE} (Xiaomi Pad 5) - generated by nabu-os4-port

properties() { '
kernel.string=${DEVICE} 4.14.180 (${BRANCH}@${SHA})
do.devicecheck=1
do.modules=0
do.systemless=1
do.cleanup=1
do.cleanuponabort=0
device.name1=${DEVICE}
device.name2=
device.name3=
device.name4=
device.name5=
supported.versions=
supported.patchlevels=
supported.vendorpatchlevels=
'; }

boot_attributes() {
set_perm_recursive 0 0 755 644 \$RAMDISK/*;
set_perm_recursive 0 0 750 750 \$RAMDISK/init* \$RAMDISK/sbin;
}

BLOCK=/dev/block/bootdevice/by-name/boot;
IS_SLOT_DEVICE=1;
RAMDISK_COMPRESSION=auto;
PATCH_VBMETA_FLAG=auto;

. tools/ak3-core.sh;

dump_boot;
write_boot;
EOF

ZIP_NAME="${DEVICE}-kernel-${BRANCH}-${SHA}.zip"
( cd "$WORK" && zip -r9 "$OUTDIR/$ZIP_NAME" . -x '*.git*' >/dev/null )
echo "package: $OUTDIR/$ZIP_NAME"
ls -lh "$OUTDIR/$ZIP_NAME"
